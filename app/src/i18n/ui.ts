const DICT: Record<UiLocale, Record<UiKey, string>> = { fr, en, ar };

export function t(locale: UiLocale, key: UiKey, vars: Record<string, string | number> = {}): string {
  return DICT[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** Texte de contenu dans la langue d'interface, avec repli sur l'anglais (l'arabe est facultatif). */
export function loc(locale: UiLocale, text: Localized): string {
  return text[locale] ?? text.en;
}

export function isLocale(x: string | undefined): x is UiLocale {
  return !!x && (UI_LOCALES as readonly string[]).includes(x);
}

/** Choix de la langue d'interface à partir des langues du navigateur (US-001, D18). */
export function negotiate(browser: readonly string[]): UiLocale {
  for (const tag of browser) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLocale(base)) return base;
  }
  return DEFAULT_LOCALE;
}
